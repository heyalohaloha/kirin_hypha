#!/usr/bin/env node
// Embeds installer_user_cleanup.ps1 into the Inno recipe as Windows PowerShell -EncodedCommand
// text (UTF-16LE, Base64) for its two modes. `--write` refreshes the generated block in
// kirin-hypha-installer.iss; the installer tests compare the recipe with this output.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const SCRIPT_PATH = path.join(here, 'installer_user_cleanup.ps1');
export const RECIPE_PATH = path.join(here, 'kirin-hypha-installer.iss');
export const MODES = { check: 'HyphaUserCleanupCheckCommand', remove: 'HyphaUserCleanupRemoveCommand' };
const BEGIN = '// BEGIN generated by scripts/windows/installer_user_cleanup.mjs from installer_user_cleanup.ps1';
const END = '// END generated by scripts/windows/installer_user_cleanup.mjs';
const CHUNK = 96;

export function cleanupScript(mode, script = fs.readFileSync(SCRIPT_PATH, 'utf8')) {
  if (!Object.hasOwn(MODES, mode)) throw new Error(`unknown cleanup mode: ${mode}`);
  if (/[^\x09\x0a\x0d\x20-\x7e]/.test(script)) throw new Error('installer_user_cleanup.ps1 must stay ASCII');
  return `$Mode = '${mode}'\r\n${script.replace(/\r?\n/g, '\r\n')}`;
}

export function encodedCommand(mode, script) {
  return Buffer.from(cleanupScript(mode, script), 'utf16le').toString('base64');
}

export function generatedBlock(script) {
  const lines = [BEGIN];
  for (const [mode, name] of Object.entries(MODES)) {
    const encoded = encodedCommand(mode, script);
    const chunks = encoded.match(new RegExp(`.{1,${CHUNK}}`, 'g'));
    lines.push(`function ${name}: String;`, 'begin', '  Result :=');
    chunks.forEach((chunk, index) => lines.push(`    '${chunk}'${index === chunks.length - 1 ? ';' : ' +'}`));
    lines.push('end;', '');
  }
  lines.push(END);
  return lines.join('\n');
}

export function embeddedBlock(recipe = fs.readFileSync(RECIPE_PATH, 'utf8')) {
  const start = recipe.indexOf(BEGIN);
  const end = recipe.indexOf(END);
  if (start < 0 || end < start || recipe.indexOf(BEGIN, start + 1) >= 0) throw new Error('recipe has no single generated cleanup block');
  return recipe.slice(start, end + END.length);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const recipe = fs.readFileSync(RECIPE_PATH, 'utf8');
  const next = recipe.replace(embeddedBlock(recipe), generatedBlock());
  if (process.argv[2] === '--write') fs.writeFileSync(RECIPE_PATH, next);
  else if (next !== recipe) { console.error('kirin-hypha-installer.iss cleanup block is stale; run with --write'); process.exitCode = 1; }
}
