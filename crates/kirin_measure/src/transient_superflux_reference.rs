#[derive(Clone, Debug, Eq, PartialEq)]
pub struct SuperFluxReferenceReceipt {
    pub id: SuperFluxReferenceId,
    pub definition_hash: [u8; 32],
    pub use_contract: SuperFluxReferenceUse,
    pub realized_unique_bin_points: usize,
    pub realized_band_count: usize,
    pub bin_layout_hash: [u8; 32],
    pub layout_status: SuperFluxReferenceLayoutStatus,
    pub trace_status: SuperFluxReferenceTraceStatus,
}

impl SuperFluxReferenceReceipt {
    pub const fn ranking_eligible(&self) -> bool {
        false
    }
}

pub fn build_superflux_reference_receipt(
    contract: SuperFluxReferenceContract,
) -> Result<SuperFluxReferenceReceipt, &'static str> {
    let definition_hash = contract.definition_hash();
    let expected_definition_hash = match contract.id {
        SuperFluxReferenceId::Paper2013Online => PAPER_2013_ONLINE_DEFINITION_SHA256,
        SuperFluxReferenceId::Cpjku103Online => CPJKU_1_03_ONLINE_DEFINITION_SHA256,
    };
    if hex::encode(definition_hash) != expected_definition_hash {
        return Err("SuperFlux named reference contract mismatch");
    }
    let bins = cpjku_filter_bins(contract)?;
    let bin_layout_hash = hash_bins(&bins);
    let layout_status = match contract.id {
        SuperFluxReferenceId::Paper2013Online => {
            if contract.reported_band_count != Some(138) || bins.len() - 2 != 139 {
                return Err("paper SuperFlux band-count discrepancy changed");
            }
            SuperFluxReferenceLayoutStatus::PaperReported138ButCpjkuNumericsRealize139
        }
        SuperFluxReferenceId::Cpjku103Online => {
            if bins.len() - 2 != 141 || hex::encode(bin_layout_hash) != CPJKU_1_03_BIN_GOLDEN_SHA256
            {
                return Err("CPJKU SuperFlux bin golden mismatch");
            }
            SuperFluxReferenceLayoutStatus::VerifiedAgainstCpjku103BinGolden
        }
    };
    Ok(SuperFluxReferenceReceipt {
        id: contract.id,
        definition_hash,
        use_contract: SuperFluxReferenceUse::ExternalValidationOnlyRankingIneligible,
        realized_unique_bin_points: bins.len(),
        realized_band_count: bins.len() - 2,
        bin_layout_hash,
        layout_status,
        trace_status: SuperFluxReferenceTraceStatus::PendingNoOfficialAudioActivationGolden,
    })
}

fn cpjku_filter_bins(contract: SuperFluxReferenceContract) -> Result<Vec<u32>, &'static str> {
    if contract.fft_bins < 3
        || contract.bands_per_octave == 0
        || contract.frequency_min_millihz == 0
        || contract.frequency_max_millihz <= contract.frequency_min_millihz
    {
        return Err("invalid SuperFlux reference filter parameters");
    }
    let fmin = contract.frequency_min_millihz as f64 / 1_000.0;
    let fmax =
        (contract.frequency_max_millihz as f64 / 1_000.0).min(contract.sample_rate_hz as f64 / 2.0);
    let factor = 2.0_f64.powf(1.0 / contract.bands_per_octave as f64);
    let mut frequencies = vec![440.0];
    let mut frequency = 440.0;
    while frequency <= fmax {
        frequency *= factor;
        frequencies.push(frequency);
    }
    frequency = 440.0;
    while frequency >= fmin {
        frequency /= factor;
        frequencies.push(frequency);
    }
    frequencies.sort_by(f64::total_cmp);
    let hz_per_bin = (contract.sample_rate_hz as f64 / 2.0) / contract.fft_bins as f64;
    let mut bins = Vec::with_capacity(frequencies.len());
    for frequency in frequencies {
        let bin = numpy_round_ties_even(frequency / hz_per_bin);
        if bin < contract.fft_bins && bins.last() != Some(&bin) {
            bins.push(bin);
        }
    }
    if bins.len() < 5 {
        return Err("SuperFlux reference filter has fewer than three bands");
    }
    Ok(bins)
}

fn numpy_round_ties_even(value: f64) -> u32 {
    let lower = value.floor();
    let fraction = value - lower;
    if fraction < 0.5 || (fraction == 0.5 && (lower as u64 & 1) == 0) {
        lower as u32
    } else {
        lower as u32 + 1
    }
}

fn hash_bins(bins: &[u32]) -> [u8; 32] {
    let mut hasher = Sha256::new();
    for bin in bins {
        hasher.update(bin.to_le_bytes());
    }
    hasher.finalize().into()
}

