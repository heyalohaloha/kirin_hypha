impl SuperFluxReferenceContract {
    pub fn definition_hash(self) -> [u8; 32] {
        let mut hasher = Sha256::new();
        let reported_band_count_tag = if self.reported_band_count.is_some() {
            "reported-band-count-some"
        } else {
            "reported-band-count-none"
        };
        for field in [
            SUPERFLUX_REFERENCE_CONTRACT_VERSION,
            self.id.as_str(),
            self.parameter_source_url,
            self.parameter_source_sha256,
            self.numerical_source_url,
            self.numerical_source_revision,
            self.numerical_source_sha256,
            "external-validation-only-ranking-ineligible",
            "mono-arithmetic-mean-downmix",
            "integer-pcm-window-divided-by-dtype-max-float-unscaled",
            "online-right-aligned-python-int-truncated-floating-hop",
            self.window.hash_tag(),
            "complex-fft-first-n-over-two-bins-nyquist-excluded",
            "linear-magnitude-no-one-sided-or-window-energy-compensation",
            "a4-440-repeated-multiply-log-centers-one-corner-each-side",
            self.bin_rounding.hash_tag(),
            "unique-ascending-bin-points",
            "discard-bin-greater-than-or-equal-to-num-fft-bins",
            "triangles-start-inclusive-stop-exclusive-height-one",
            "triangle-area-not-normalized",
            reported_band_count_tag,
            self.magnitude_compression.hash_tag(),
            "past-frame-three-band-maximum-half-wave",
            self.band_reduction.hash_tag(),
            "scipy-constant-padding-inclusive-effective-peak-widths",
            "zero-delay",
            self.combine_provenance.hash_tag(),
            self.delta.hash_tag(),
        ] {
            hasher.update(field.as_bytes());
            hasher.update([0]);
        }
        for value in [
            self.sample_rate_hz,
            self.frame_size_samples,
            self.fft_bins,
            self.frame_rate_fps,
            self.hop_numerator_samples,
            self.hop_denominator_frames,
            self.bands_per_octave,
            self.frequency_min_millihz,
            self.frequency_max_millihz,
            self.reported_band_count.unwrap_or(0),
            self.spectral_lag_frames,
            self.maximum_filter_radius,
            self.maximum_filter_width,
            self.pre_max_ms,
            self.pre_avg_ms,
            self.declared_post_max_ms,
            self.declared_post_avg_ms,
            self.effective_post_max_ms,
            self.effective_post_avg_ms,
            self.combine_declared_input_micros,
            self.combine_implementation_divisor,
        ] {
            hasher.update(value.to_le_bytes());
        }
        if let SuperFluxReferenceDelta::FixedMilliLogMagnitude(value) = self.delta {
            hasher.update(value.to_le_bytes());
        }
        hasher.finalize().into()
    }

    pub fn definition_hex(self) -> String {
        hex::encode(self.definition_hash())
    }

    pub const fn pre_max_frames(self) -> u32 {
        self.frame_rate_fps * self.pre_max_ms / 1_000
    }

    pub const fn pre_avg_frames(self) -> u32 {
        self.frame_rate_fps * self.pre_avg_ms / 1_000
    }

    pub const fn effective_post_max_frames(self) -> u32 {
        self.frame_rate_fps * self.effective_post_max_ms / 1_000
    }

    pub const fn effective_post_avg_frames(self) -> u32 {
        self.frame_rate_fps * self.effective_post_avg_ms / 1_000
    }

    pub const fn effective_combine_micros(self) -> Option<u32> {
        self.combine_declared_input_micros
            .checked_div(self.combine_implementation_divisor)
    }
}

