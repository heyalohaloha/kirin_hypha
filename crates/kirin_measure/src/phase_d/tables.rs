/// Sharpness calibration constant
pub const SHARPNESS_C: f64 = 0.11;

/// Bark boundary for DIN weighting function change
pub const SHARPNESS_Z_THRESHOLD: f64 = 15.8;

/// DIN 45692 Widmann weighting function g(z)
#[inline]
pub fn sharpness_weight_din(z: f64) -> f64 {
    if z <= SHARPNESS_Z_THRESHOLD {
        1.0
    } else {
        0.15 * ((z - SHARPNESS_Z_THRESHOLD) * 0.42).exp() + 0.85
    }
}

